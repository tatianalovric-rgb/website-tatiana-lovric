// FUNCIÓN PARA CAMBIAR EL IDIOMA
// ===================================================================
function setLanguage(lang) {
  const t = translations[lang];
  if (!t) return;

  // Actualizar atributos de idioma y título del navegador
  document.documentElement.lang = lang;
  document.title = t.meta_title;
  localStorage.setItem('preferred_lang', lang);

  // Reemplazar textos de elementos con atributo data-i18n
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (t[key]) {
      el.innerHTML = t[key];
    }
  });

  // Alternar clase activa en los botones de idioma
  const btnEs = document.getElementById('btn-es');
  const btnEn = document.getElementById('btn-en');
  if (btnEs) btnEs.classList.toggle('active', lang === 'es');
  if (btnEn) btnEn.classList.toggle('active', lang === 'en');

  // Actualizar los enlaces de WhatsApp con el mensaje traducido
  const encodedMsg = encodeURIComponent(t.wa_msg);
  const waUrl = `https://wa.me/584123312425?text=${encodedMsg}`;

  const headerCta = document.getElementById('header-cta');
  const waFloat = document.getElementById('whatsapp-float');
  if (headerCta) headerCta.href = waUrl;
  if (waFloat) waFloat.href = waUrl;
}

// ===================================================================
// INICIALIZACIÓN AL CARGAR LA PÁGINA
// ===================================================================
document.addEventListener('DOMContentLoaded', () => {
  // Detectar idioma guardado previamente o tomar el idioma del navegador
  const savedLang = localStorage.getItem('preferred_lang');
  const browserLang = (navigator.language && navigator.language.startsWith('en')) ? 'en' : 'es';
  setLanguage(savedLang || browserLang);

  // Funcionalidad interactiva de los acordeones de Preguntas Frecuentes
  document.querySelectorAll('.accordion-header').forEach(header => {
    header.addEventListener('click', () => {
      const item = header.parentElement;
      const isOpen = item.classList.contains('active');

      // Cerrar otros acordeones abiertos para mantener orden visual
      document.querySelectorAll('.accordion-item').forEach(i => i.classList.remove('active'));

      // Abrir el seleccionado si estaba cerrado
      if (!isOpen) {
        item.classList.add('active');
      }
    });
  });

  // Funcionalidad del Menú Móvil (Hamburguesa)
  const toggleBtn = document.getElementById('nav-toggle');
  const navMenu = document.getElementById('nav-menu');
  if (toggleBtn && navMenu) {
    toggleBtn.addEventListener('click', () => {
      navMenu.classList.toggle('active');
      toggleBtn.classList.toggle('open');
    });

    // Cerrar automáticamente el menú al hacer clic en cualquier enlace
    document.querySelectorAll('.nav-link').forEach(link => {
      link.addEventListener('click', () => {
        navMenu.classList.remove('active');
        toggleBtn.classList.remove('open');
      });
    });
  }
});
